-- Creating table through query because manually all data is not uploading 
CREATE TABLE spotify_tracks (
    row_index INT,                  
    track_id VARCHAR(50),
    artists TEXT,
    album_name TEXT,
    track_name TEXT,
    popularity INT,
    duration_ms INT,
    explicit VARCHAR(10),           -- Boolean values 
    danceability DECIMAL(5,4),
    energy DECIMAL(5,4),
    `key` INT,
    loudness DECIMAL(5,3),
    `mode` INT,
    speechiness DECIMAL(5,4),
    acousticness DECIMAL(5,4),
    instrumentalness DECIMAL(7,6),
    liveness DECIMAL(5,4),
    valence DECIMAL(5,4),
    tempo DECIMAL(6,3),
    time_signature INT,
    track_genre VARCHAR(50)
);
